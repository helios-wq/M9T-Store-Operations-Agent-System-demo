def _render_doc(d: dict, variant: str = "") -> str:
    lines = [f"# 问题类别：{d['category']}：{d['title']}{variant}", "", "## 操作步骤"]
    lines += [f"{i + 1}. {s}" for i, s in enumerate(d["steps"])]
    lines += ["", "## 注意事项"]
    lines += [f"- {n}" for n in d["notices"]]
    if d.get("faqs"):
        lines += ["", "## 常见问题"]
        lines += [f"- {f}" for f in d["faqs"]]
    return "\n".join(lines)


def generate_docs(min_docs: int = 300, seed: int = 7) -> int:
    out_dir = settings.raw_docs_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = random.Random(seed)
    docs = []
    # 1) 种子文档（doc_id 保持与评测集 ground truth 一致，不追加后缀）
    for d in CURATED_DOCS:
        docs.append((d["doc_id"], d))
    # 2) 扩充主题 × 变体
    for t in TOPICS:
        category, key, title, steps, notices = t
        base = {"doc_id": key, "title": title, "category": category, "steps": steps, "notices": notices}
        for v in VARIANTS:
            docs.append((f"{key}-v{rng.randrange(1000, 9999)}", base))
    # 3) 若仍不足，复制种子变体补齐
    while len(docs) < min_docs:
        d = CURATED_DOCS[len(docs) % len(CURATED_DOCS)]
        docs.append((f"{d['doc_id']}-fill{len(docs)}", d))

    for doc_id, d in docs:
        (out_dir / f"{doc_id}.md").write_text(_render_doc(d), encoding="utf-8")

    # 清理旧文件
    for old in out_dir.glob("*.md"):
        if old.stem not in {did for did, _ in docs}:
            old.unlink()
    return len(docs)


